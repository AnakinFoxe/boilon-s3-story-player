"""Write main/boards/boilon-s3-gen2/p5_1_ui_font.h from LVGL's unscii-8 source.

unscii-8 is public domain (Viznut); LVGL ships it as lv_font_unscii_8.c. Only
printable ASCII is kept, in LVGL's own box format, so the device, the host
tests and the prototype read the same glyphs. Run once after an LVGL update:
    python3 docs/boilon/p5_1_prototype/gen_unscii.py
"""
import os
import re
from pathlib import Path

ROOT = Path(os.environ.get('BOILON_ROOT') or Path(__file__).resolve().parents[3])
SOURCE = ROOT / 'managed_components/lvgl__lvgl/src/font/lv_font_unscii_8.c'
TARGET = Path(__file__).resolve().parents[3] / 'main/boards/boilon-s3-gen2/p5_1_ui_font.h'


def main():
    src = SOURCE.read_text()
    bm = src[src.index('glyph_bitmap[] = {'):]
    data = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', bm[:bm.index('};')])]
    ds = src[src.index('glyph_dsc[] = {'):]
    dsc = [tuple(int(v) for v in m) for m in re.findall(
        r'\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), \.box_h = (\d+), '
        r'\.ofs_x = (-?\d+), \.ofs_y = (-?\d+)', ds[:ds.index('};')])]
    entries, bitmap = [], []
    for cp in range(32, 127):
        index, adv, w, h, x, y = dsc[cp - 32 + 1]
        size = (w * h + 7) // 8
        entries.append(f'{{{adv // 16}, {w}, {h}, {x}, {y}, {len(bitmap)}}}')
        bitmap.extend(data[index:index + size])
    lines = [
        '#pragma once',
        '// SPDX-License-Identifier: CC0-1.0 OR LicenseRef-Public-Domain (unscii by Viznut)',
        '// unscii-8, printable ASCII, from LVGL 9 src/font/lv_font_unscii_8.c (1 bpp, packed',
        '// rows without padding). Generated by docs/boilon/p5_1_prototype/gen_unscii.py.',
        '#include <cstdint>',
        '',
        'namespace boilon::ui::unscii {',
        'constexpr int kLineHeight = 9, kBaseLine = 0;',
        'struct Box {',
        '    uint8_t adv, w, h;',
        '    int8_t x, y;',
        '    uint16_t offset;',
        '};',
        '// Code points 32..126.',
        'constexpr Box kBoxes[] = {',
    ]
    for i in range(0, len(entries), 6):
        lines.append('    ' + ', '.join(entries[i:i + 6]) + ',')
    lines.append('};')
    lines.append('constexpr uint8_t kBits[] = {')
    for i in range(0, len(bitmap), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in bitmap[i:i + 16]) + ',')
    lines.append('};')
    lines.append('}  // namespace boilon::ui::unscii')
    TARGET.write_text('\n'.join(lines) + '\n')
    print(f'{TARGET}: {len(entries)} glyphs, {len(bitmap)} bitmap bytes, {len(lines)} lines')


if __name__ == '__main__':
    main()
